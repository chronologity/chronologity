import { Column, Entity, Index, PrimaryColumn } from "typeorm";

/**
 * The Search index.
 *
 * Derived, disposable, rebuildable state. Never authoritative for anything: a
 * document is a copy of what a domain table already owns, kept so that finding
 * is possible without scanning history.
 *
 * Describes a table the migrations own (ADR-099). The DataSource runs with
 * `synchronize` off, so nothing here alters a column.
 */
@Entity("search_documents")
@Index("search_documents_author_idx", ["indexVersion", "authorUserId"])
export class SearchDocument {
  /**
   * Which index version this row belongs to.
   *
   * Part of the key rather than a filter, so a rebuild of one version cannot
   * overwrite another and cutover is the read path changing which it asks for.
   */
  @PrimaryColumn("text", { name: "index_version" })
  indexVersion!: string;

  /** `moment`, `user`, `event`, or `location`. Constrained by the database. */
  @PrimaryColumn("text", { name: "entity_type" })
  entityType!: string;

  /** Stable Chronologity identity, independent of names and aliases. */
  @PrimaryColumn("uuid", { name: "entity_id" })
  entityId!: string;

  @Column("text")
  title!: string;

  @Column("text")
  body!: string;

  /** What the thing has also been called. For historical Events, not a nicety. */
  @Column("text")
  aliases!: string;

  /**
   * The lexical index.
   *
   * Written by the document builder rather than generated by the database,
   * because the field weights are part of the index version: changing them
   * produces a new version built beside the old one.
   */
  @Column("tsvector", { name: "search_vector" })
  searchVector!: string;

  /** Null for a User and a Location, which are not occurrences. */
  @Column("timestamptz", { name: "occurrence_start", nullable: true })
  occurrenceStart!: Date | null;

  @Column("timestamptz", { name: "occurrence_end", nullable: true })
  occurrenceEnd!: Date | null;

  /** Kept so a temporal filter never invents a day for a summer nobody dated. */
  @Column("text", { name: "occurrence_precision", nullable: true })
  occurrencePrecision!: string | null;

  @Column("timestamptz", { name: "published_at", nullable: true })
  publishedAt!: Date | null;

  /** Intrinsic eligibility. The viewer-dependent half is resolved at query time. */
  @Column("text")
  visibility!: string;

  /** A separate dimension from visibility: accessible does not mean indexable. */
  @Column("boolean")
  searchable!: boolean;

  @Column("text", { name: "moderation_state" })
  moderationState!: string;

  @Column("boolean")
  deleted!: boolean;

  /**
   * Whose it is, where it is anybody's.
   *
   * Not eligibility itself — it is what lets the query path resolve blocking and
   * suspension against one column rather than joining back through the content
   * tables. Null for an Event or a Location, which nobody authors.
   */
  @Column("uuid", { name: "author_user_id", nullable: true })
  authorUserId!: string | null;

  @Column("text", { name: "geohash_exact", nullable: true })
  geohashExact!: string | null;

  @Column("text", { name: "geohash_coarse", nullable: true })
  geohashCoarse!: string | null;

  @Column("text", { name: "geohash_region", nullable: true })
  geohashRegion!: string | null;

  @Column("double precision", { nullable: true })
  significance!: number | null;

  @Column("text", { name: "significance_version", nullable: true })
  significanceVersion!: string | null;

  /**
   * Per-field origin.
   *
   * Declared as `object` for the reason the audit tables' `context` is: the
   * driver serialises whatever it is given, and an open index signature does not
   * satisfy the query builder's deep-partial of the column type.
   */
  @Column("jsonb")
  provenance!: object;

  /** When this was built from authoritative state. The regression guard. */
  @Column("timestamptz", { name: "built_at" })
  builtAt!: Date;

  @Column("uuid", { name: "source_event_id", nullable: true })
  sourceEventId!: string | null;

  @Column("timestamptz", { name: "indexed_at" })
  indexedAt!: Date;
}
