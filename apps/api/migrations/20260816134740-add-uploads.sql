-- Applied in filename order, once, inside a transaction. Editing this file
-- after it has been applied anywhere changes nothing: write a new migration.
--
-- Uploads: media on its way into Chronologity.

-- The Upload read model.
--
-- An Upload belongs to a User, not to a Moment. Media exists before
-- publication, which is what makes drafts, retries, and abandonment possible;
-- association with a Moment arrives when Moments do.
CREATE TABLE uploads (
    upload_id     uuid        PRIMARY KEY,
    owner_user_id uuid        NOT NULL,
    kind          text        NOT NULL,

    -- What the client said it would send. Kept as claims rather than facts, so
    -- that a mismatch between claim and stored object is answerable later.
    declared_content_type text    NOT NULL,
    declared_byte_size    bigint  NOT NULL,

    -- Where the bytes are. Generated by the server and recorded here rather
    -- than recomputed: it is the only pointer to the object, and a rule that
    -- derived it would orphan objects the day the rule changed.
    storage_key   text        NOT NULL UNIQUE,

    state         text        NOT NULL DEFAULT 'registered',

    -- What storage actually reported, once the server has looked. Null until
    -- then, which is the difference between "claimed" and "verified".
    byte_size     bigint,
    content_type  text,
    checksum      text,

    -- Shown to the owner, so it describes the media rather than the
    -- infrastructure.
    failure_reason text,

    registered_at timestamptz NOT NULL,
    -- After this instant the registration can no longer be finalized.
    expires_at    timestamptz NOT NULL,
    received_at   timestamptz,
    updated_at    timestamptz NOT NULL DEFAULT now()
);

-- Listing someone's own uploads, newest first, is the common read.
CREATE INDEX uploads_owner_idx ON uploads (owner_user_id, registered_at DESC);

-- Finding registrations that lapsed without arriving, so their authorisation
-- can be cleaned up rather than lingering.
CREATE INDEX uploads_expiry_idx
    ON uploads (expires_at)
    WHERE state = 'registered';
